export function loadLanguage(): AppLanguage {
	try {
		const stored = localStorage.getItem(STORAGE_KEY);
		if (stored === "en" || stored === "zh-CN") return stored;
	} catch {
		/* Storage is optional. */
	}
	return navigator.language.toLowerCase().startsWith("zh") ? "zh-CN" : "en";
}

export function translate(language: AppLanguage, key: string, values?: TranslationValues): string {
	const template = language === "zh-CN" ? (zhCN[key] ?? key) : key;
	if (!values) return template;
	return template.replace(/\{(\w+)\}/g, (match, name: string) => String(values[name] ?? match));
}

const I18nContext = createContext<I18nValue | undefined>(undefined);

export function I18nProvider({ children }: { readonly children: ReactNode }): React.JSX.Element {
	const [language, setLanguageState] = useState<AppLanguage>(loadLanguage);
	useEffect(() => {
		document.documentElement.lang = language;
		try {
			localStorage.setItem(STORAGE_KEY, language);
		} catch {
			/* Storage is optional. */
		}
	}, [language]);
	const value = useMemo<I18nValue>(
		() => ({
			language,
			setLanguage: setLanguageState,
			t: (key, values) => translate(language, key, values),
		}),
		[language],
	);
	return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n(): I18nValue {
	const value = useContext(I18nContext);
	if (!value) throw new Error("useI18n must be used inside I18nProvider");
	return value;
}
